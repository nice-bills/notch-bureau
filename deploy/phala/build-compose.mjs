#!/usr/bin/env node
// Builds deploy/phala/docker-compose.yml: the ONE file that defines what runs inside the CVM.
//
// There is no image to push. The compose file starts a public base image (pinned by digest) and carries the
// whole underwriter as a gzip+base64 bundle in an environment value, so the code is part of the compose file,
// and the compose file's sha256 (compose-hash) is extended into RTMR3 of the TDX quote. Same code => same
// compose-hash => same measurement. Anyone can rebuild the bundle from this repo and compare
// (enclave/scripts/verify-attestation.mjs --repo does exactly that).
//
//   node deploy/phala/build-compose.mjs            # writes deploy/phala/docker-compose.yml
//   node deploy/phala/build-compose.mjs --check    # exits 1 if the committed file differs from a fresh build
//
// Secrets are NEVER in here. The LLM key/url/model reach the CVM only as Phala encrypted environment variables
// (listed by name under `environment:` with no value, so Phala injects them at boot).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');

export const BASE_IMAGE = 'node:22-slim@sha256:e9f565d32859f0cbfb52125eafe8be39390f24dac302dc3cdf566e8ba3ab21ee';
export const NOTCH_ENV = {
  DEMO_FIXTURES: '1', // demo/e2e build: trusts the synthetic DKIM key. Shown in /attestation. Remove for production.
  PORT: '8787',
  SOLANA_RPC_URL: 'https://api.devnet.solana.com',
  NOTCH_PROGRAM_ID: '4ucSsrca8WS9LxJvoQZdhFscYnZ8DGDKMYcBhmBNPLVz',
  NOTCH_USDC_MINT: '8w1jur5oikV5aax7Q8eTSZwfZwVvFQDTknMTREJ75NNS', // devnet test USDC
};
// Names only (values come from Phala's encrypted env): never put a value here.
export const SEALED_ENV = ['NOTCH_LLM_URL', 'NOTCH_LLM_MODEL', 'NOTCH_LLM_KEY', 'NOTCH_LLM_TIMEOUT_MS'];

/** Files that make up the bundle: bundle path -> repo path. Sorted, so the bundle is deterministic. */
export function bundleFiles() {
  const map = new Map();
  map.set('package.json', path.join(here, 'package.json'));
  map.set('package-lock.json', path.join(here, 'package-lock.json'));
  map.set('enclave/package.json', path.join(root, 'enclave', 'package.json'));
  for (const f of fs.readdirSync(path.join(root, 'enclave', 'src')).sort()) {
    if (f.endsWith('.js')) map.set(`enclave/src/${f}`, path.join(root, 'enclave', 'src', f));
  }
  map.set('enclave/test/fixtures/emails.js', path.join(root, 'enclave', 'test', 'fixtures', 'emails.js'));
  return new Map([...map.entries()].sort(([a], [b]) => (a < b ? -1 : 1)));
}

export function buildBundle() {
  const obj = {};
  for (const [k, p] of bundleFiles()) obj[k] = fs.readFileSync(p).toString('base64');
  const json = JSON.stringify(obj); // keys already sorted
  // Dotted every 16 characters: Phala's deploy filter rejects some long random-looking alphanumeric runs
  // ("violates our terms of use"), and a gzip+base64 blob contains them by chance. The CVM strips the dots.
  const b64 = zlib.gzipSync(Buffer.from(json), { level: 9, mtime: 0 }).toString('base64').replace(/(.{16})/g, '$1.').replace(/\.$/, '');
  return { b64, files: Object.fromEntries([...bundleFiles()].map(([k, p]) => [k, crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex')])) };
}

// Unpack the bundle, install from the lockfile (integrity-pinned), start the server.
const UNPACK = 'const z=require("zlib"),f=require("fs"),p=require("path");'
  + 'const b=JSON.parse(z.gunzipSync(Buffer.from(process.env.NOTCH_BUNDLE.replace(/\\./g,""),"base64")));'
  + 'for(const[k,v]of Object.entries(b)){f.mkdirSync(p.dirname(k),{recursive:true});f.writeFileSync(k,Buffer.from(v,"base64"))}';
export const START = `node -e '${UNPACK}' && npm ci --ignore-scripts --no-audit --no-fund && exec node enclave/src/cvm-server.js`;

export function composeText() {
  const { b64 } = buildBundle();
  const q = (s) => JSON.stringify(s); // JSON strings are valid YAML double-quoted scalars; "$" is escaped for compose below
  const esc = (s) => s.replace(/\$/g, '$$$$');
  const lines = [
    '# GENERATED by deploy/phala/build-compose.mjs. Do not edit by hand.',
    '# The whole underwriter is the NOTCH_BUNDLE value below (gzip+base64 JSON of enclave/src, the DKIM test fixtures,',
    '# package.json and package-lock.json). Verify it against the repo with enclave/scripts/verify-attestation.mjs --repo.',
    'services:',
    '  underwriter:',
    `    image: ${BASE_IMAGE}`,
    '    working_dir: /app',
    '    restart: unless-stopped',
    `    command: ["sh", "-c", ${q(esc(START))}]`,
    '    ports:',
    '      - "8787:8787"',
    '    volumes:',
    '      - /var/run/dstack.sock:/var/run/dstack.sock',
    '    environment:',
    ...Object.entries(NOTCH_ENV).map(([k, v]) => `      ${k}: ${q(v)}`),
    // Sealed (encrypted) values, injected by Phala at boot. Listed by name only.
    ...SEALED_ENV.map((k) => `      ${k}: \${${k}:-}`),
    `      NOTCH_BUNDLE: ${q(b64)}`,
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(here, 'docker-compose.yml');
  const text = composeText();
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text;
    console.log(same ? 'docker-compose.yml is up to date' : 'docker-compose.yml is STALE: run node deploy/phala/build-compose.mjs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(root, out)} (${text.length} bytes)`);
}
